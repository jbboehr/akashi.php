namespace jbboehr\Akashi\Execution;

/**
 * @logion [AWC 57:15] The physician marked whether the wound arose beneath the blade or beneath the bandage, for one
 *     grief may require two remedies and neither is served by an unnamed hour.
 */
enum FailurePhase: string
{
    /**
     * @logion [SFA 57:16] The bell cracked while sounding the appointed note; its silence therefore belonged to the
     *     rite itself and not to the hands that later gathered the fragments.
     */
    case Execution = 'execution';

    /**
     * @logion [OSD 57:17] The procession crossed unharmed, yet the gate could not be shut behind it; success was
     *     withheld until the road ceased to endanger those who followed.
     */
    case Cleanup = 'cleanup';
}
